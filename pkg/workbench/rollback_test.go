func TestNormalizeSiteURL(t *testing.T) {
	t.Parallel()
	tests := map[string]string{
		"HTTPS://Repo.Example.ORG:443/path/": "https://repo.example.org/path",
		"http://repo.example.org:80":         "http://repo.example.org",
		"https://repo.example.org:8443/site": "https://repo.example.org:8443/site",
		"http://[2001:db8::1]:8080/drupal":   "http://[2001:db8::1]:8080/drupal",
	}
	for input, want := range tests {
		input, want := input, want
		t.Run(input, func(t *testing.T) {
			t.Parallel()
			got, err := NormalizeSiteURL(input)
			if err != nil {
				t.Fatal(err)
			}
			if got != want {
				t.Fatalf("origin = %q, want %q", got, want)
			}
		})
	}
	for _, input := range []string{"repo.example.org", "ftp://repo.example.org", "https://user:pass@repo.example.org", "https://repo.example.org?other=site"} {
		if _, err := NormalizeSiteURL(input); err == nil {
			t.Fatalf("unsafe origin %q unexpectedly accepted", input)
		}
	}
}
