package workbench

import (
	"reflect"
	"strings"
	"testing"
)

func TestParseRollbackCSVAcceptsWorkbenchArtifact(t *testing.T) {
	t.Parallel()
	input := " \ufeff node_id , id , title , field_member_of , file \n# generated by Workbench\n42,a,One,,one.tif\n77,b,Two,42,two.tif\n"
	ids, err := ParseRollbackCSV(strings.NewReader(input))
	if err != nil {
		t.Fatal(err)
	}
	if want := []uint64{42, 77}; !reflect.DeepEqual(ids, want) {
		t.Fatalf("IDs = %#v, want %#v", ids, want)
	}
}

func TestParseRollbackCSVRejectsUnsafeArtifacts(t *testing.T) {
	t.Parallel()
	tests := map[string]string{
		"wrong header":     "id\n42\n",
		"invalid ID":       "node_id\nnot-a-node\n",
		"zero ID":          "node_id\n0\n",
		"duplicate":        "node_id\n42\n42\n",
		"duplicate header": "node_id,node_id\n42,999\n",
		"empty header":     "node_id,\n42,extra\n",
		"no rows":          "node_id\n# none\n",
	}
	for name, input := range tests {
		name, input := name, input
		t.Run(name, func(t *testing.T) {
			t.Parallel()
			if _, err := ParseRollbackCSV(strings.NewReader(input)); err == nil {
				t.Fatal("unsafe rollback artifact unexpectedly accepted")
			}
		})
	}
}

func TestParseRollbackCSVNumbersRecordsAcrossComments(t *testing.T) {
	t.Parallel()
	_, err := ParseRollbackCSV(strings.NewReader("node_id\n42\n# generated comment\n42\n"))
	if err == nil || !strings.Contains(err.Error(), "records 2 and 3") {
		t.Fatalf("duplicate node error = %v, want records 2 and 3", err)
	}
}

func TestParseRollbackCSVReportsWidthMismatchRecord(t *testing.T) {
	t.Parallel()
	_, err := ParseRollbackCSV(strings.NewReader("node_id,title\n42\n"))
	if err == nil || !strings.Contains(err.Error(), "record 2 has 1 columns, want 2") {
		t.Fatalf("width mismatch error = %v", err)
	}
}

func TestValidateGuardedExecutionConfig(t *testing.T) {
	t.Parallel()
	for _, task := range []string{"add_media", "delete"} {
		cfg, err := ValidateGuardedExecutionConfig(strings.NewReader("task: "+task+"\nhost: https://repo.example.org\n"), task)
		if err != nil {
			t.Fatalf("%s config error = %v", task, err)
		}
		if cfg.Task != task || cfg.Host != "https://repo.example.org" {
			t.Fatalf("%s config = %#v", task, cfg)
		}
	}
	for setting, value := range map[string]string{
		"bootstrap":                        "[/tmp/hook]",
		"completion_message":               "Media created successfully",
		"csv_row_filters":                  "[{field: id}]",
		"input_data_zip_archives":          "[https://example.org/input.zip]",
		"log_response_body":                "true",
		"preprocessors":                    "{title: /tmp/preprocess}",
		"remove_password_from_config_file": "true",
		"secondary_tasks":                  "[other.yml]",
	} {
		input := "task: add_media\nhost: https://repo.example.org\n" + setting + ": " + value + "\n"
		if _, err := ValidateGuardedExecutionConfig(strings.NewReader(input), "add_media"); err == nil || !strings.Contains(err.Error(), setting) {
			t.Fatalf("setting %s error = %v", setting, err)
		}
	}
	if _, err := ValidateGuardedExecutionConfig(strings.NewReader("task: add_media\nhost: https://repo.example.org\nadditional_files: [{supplemental_file: 16}]\n"), "add_media"); err == nil {
		t.Fatal("additional_files unexpectedly accepted")
	}
	if _, err := ValidateGuardedExecutionConfig(strings.NewReader("task: delete\nhost: https://repo.example.org\nprompt_user_before_delete_task: true\n"), "delete"); err == nil {
		t.Fatal("nested delete prompt unexpectedly accepted")
	}
}

func TestGuardedConfigSnapshotPinsOnlyRequestedLog(t *testing.T) {
	t.Parallel()
	input := []byte("task: add_media\nhost: https://repo.example.org\nlog_file_path: logs/legacy.log\nlog_file_mode: a\n")
	snapshot, cfg, err := GuardedConfigSnapshot(input, "add_media", "/var/log/workbench/retry.log")
	if err != nil {
		t.Fatal(err)
	}
	if cfg.Host != "https://repo.example.org" {
		t.Fatalf("config = %#v", cfg)
	}
	text := string(snapshot)
	if !strings.Contains(text, "log_file_path: /var/log/workbench/retry.log") || !strings.Contains(text, "log_file_mode: w") || strings.Contains(text, "legacy.log") {
		t.Fatalf("snapshot = %q", text)
	}
}

